using System.Collections.Generic;
using System.Collections.Immutable;
using System.Text;

using Microsoft.CodeAnalysis.Text;

namespace NativeWeb.Permissions.Generator;

// The emitted text. Two shapes: one constants class per model, one catalog per
// assembly.
internal static class PermissionsEmitter
{
    private const string Permission = "global::NativeWeb.Permissions.Permission";
    private const string ReadOnlyList = "global::System.Collections.Generic.IReadOnlyList";

    // static class ArticlePermissions in the model's own namespace.
    //
    // In the model's namespace rather than one shared Permissions tree, for two
    // reasons: a shared root class would collide with the NativeWeb.Permissions
    // namespace at every use site that has a using for it, and the constants belong
    // beside the model they describe, where a reader looking at Article finds them.
    internal static SourceText Constants(PermissionModel model, string scope, ImmutableArray<string> actions)
    {
        var built = new StringBuilder();
        built.AppendLine("// <auto-generated/>");
        built.AppendLine("#nullable enable");
        built.AppendLine();

        if (model.Namespace.Length > 0)
        {
            built.Append("namespace ").Append(model.Namespace).AppendLine(";");
            built.AppendLine();
        }

        string className = PermissionNaming.ConstantsClassName(model.TypeName);

        built.Append("/// <summary>The permissions declared by <see cref=\"")
             .Append(model.TypeName)
             .AppendLine("\"/>.</summary>");
        built.Append("public static class ").AppendLine(className);
        built.AppendLine("{");

        foreach (string action in actions)
        {
            string name = PermissionNaming.ConstantName(action);
            string full = PermissionNaming.Compose(scope, model.TypeName, action);

            built.Append("    /// <summary>The <c>").Append(action).AppendLine("</c> permission.</summary>");
            built.Append("    public static readonly ").Append(Permission).Append(' ').Append(name)
                 .Append(" = new ").Append(Permission).Append("(\"").Append(full).AppendLine("\");");
            built.AppendLine();
        }

        built.Append("    /// <summary>Every permission this model declares.</summary>");
        built.AppendLine();
        built.Append("    public static readonly ").Append(ReadOnlyList).Append('<').Append(Permission)
             .AppendLine("> All = new[]");
        built.AppendLine("    {");

        foreach (string action in actions)
        {
            built.Append("        ").Append(PermissionNaming.ConstantName(action)).AppendLine(",");
        }

        built.AppendLine("    };");
        built.AppendLine("}");

        return SourceText.From(built.ToString(), Encoding.UTF8);
    }

    // internal static class PermissionCatalog in the global namespace, so that
    // Program.cs reaches it with no using. Internal because it is this assembly's
    // own declaration list and means nothing to anyone else.
    internal static SourceText Catalog(IReadOnlyList<string> qualifiedConstants)
    {
        var built = new StringBuilder();
        built.AppendLine("// <auto-generated/>");
        built.AppendLine("#nullable enable");
        built.AppendLine();
        built.AppendLine("/// <summary>Every permission this assembly declares.</summary>");
        built.AppendLine("/// <remarks>");
        built.AppendLine("/// Pass to <c>services.AddPermissions(PermissionCatalog.All)</c>. A grant naming");
        built.AppendLine("/// anything outside this list is dropped when a subject&#39;s permissions are");
        built.AppendLine("/// resolved, which is what makes a removed declaration stop granting.");
        built.AppendLine("/// </remarks>");
        built.AppendLine("internal static class PermissionCatalog");
        built.AppendLine("{");
        built.AppendLine("    /// <summary>Every declared permission, in declaration order.</summary>");
        built.Append("    public static readonly ").Append(ReadOnlyList).Append('<').Append(Permission)
             .Append("> All =");

        // An implicitly-typed empty array is CS0826, and the empty case is reached:
        // an assembly whose only model was declined still emits this file, so the
        // author's AddPermissions(PermissionCatalog.All) compiles and the build
        // fails on the diagnostic rather than on a name that went missing.
        if (qualifiedConstants.Count == 0)
        {
            built.Append(" global::System.Array.Empty<").Append(Permission).AppendLine(">();");
        }
        else
        {
            built.AppendLine(" new[]");
            built.AppendLine("    {");

            foreach (string constant in qualifiedConstants)
            {
                built.Append("        ").Append(constant).AppendLine(",");
            }

            built.AppendLine("    };");
        }
        built.AppendLine("}");

        return SourceText.From(built.ToString(), Encoding.UTF8);
    }
}
