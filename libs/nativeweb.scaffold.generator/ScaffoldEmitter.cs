        sb.AppendLine("        IAntiforgery? antiforgery = http.RequestServices.GetService<IAntiforgery>();");
        sb.AppendLine("        if (antiforgery is null)");
        sb.AppendLine("        {");
        sb.AppendLine("            return string.Empty;");
