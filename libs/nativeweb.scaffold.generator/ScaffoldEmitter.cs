        sb.AppendLine();
        sb.AppendLine("        await store.CreateAsync(item, ct).ConfigureAwait(false);");
        sb.AppendLine("        return Results.Redirect(BasePath);");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

