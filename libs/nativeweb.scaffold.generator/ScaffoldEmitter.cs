        string indexPath = root.Length == 0 ? "/" : root;

        var sb = new StringBuilder(8192);
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// Generated by NativeWeb.Scaffold.Generator. Do not edit.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
