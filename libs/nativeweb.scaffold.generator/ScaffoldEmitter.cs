        sb.AppendLine("        return \"<input type=\\\"hidden\\\" name=\\\"\" + HtmlEncoder.Default.Encode(tokens.FormFieldName)");
        sb.AppendLine("            + \"\\\" value=\\\"\" + HtmlEncoder.Default.Encode(tokens.RequestToken ?? string.Empty) + \"\\\">\";");
