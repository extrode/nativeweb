using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace NativeWeb.Scaffold.Generator;

// Emits the CRUD route group, the self-binding form record, and the HTML for
// every view. One file per model, plus one shared runtime file.
internal static class ScaffoldEmitter
{
    public static string Emit(ScaffoldModel model, string root)
    {
        var sb = new StringBuilder(8192);
        string type = model.FullyQualifiedName;
        string cls = model.TypeName + "Scaffold";
        string form = model.TypeName + "Form";
        string route = root + "/" + model.Route;

        var editable = model.Properties.Where(p => !p.ReadOnly).ToList();
        var listed = model.Properties.Where(p => p.InList).ToList();
        if (listed.Count == 0)
        {
            listed = model.Properties.Take(4).ToList();
        }

        var searchable = model.Properties.Where(p => p.Searchable).ToList();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// Generated by NativeWeb.Scaffold.Generator. Do not edit.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        // Stated rather than assumed. Every one of these arrives free from
        // ImplicitUsings in a default SDK project, which is why the omission went
        // unnoticed: a consumer with <ImplicitUsings>disable</ImplicitUsings> got
        // generated code that would not compile, on a model that had declared
        // nothing unusual. Found by compiling the generator's output in a bare
        // compilation (EverySupportedPropertyType_EmitsCodeThatCompiles), not by
        // reading it.
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Reflection;");
        sb.AppendLine("using System.Text;");
        sb.AppendLine("using System.Text.Encodings.Web;");
        sb.AppendLine("using System.Threading;");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine();
        sb.AppendLine("using Microsoft.AspNetCore.Builder;");
        sb.AppendLine("using Microsoft.AspNetCore.Http;");
        sb.AppendLine("using Microsoft.AspNetCore.Routing;");
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        sb.AppendLine();
        sb.AppendLine("using NativeWeb.Scaffold;");
        sb.AppendLine();
        sb.AppendLine("namespace NativeWeb.Scaffold.Generated;");
        sb.AppendLine();

        EmitFormRecord(sb, model, form, editable);

        sb.AppendLine($"/// <summary>Generated CRUD endpoints for <see cref=\"{type}\"/>.</summary>");
        sb.AppendLine($"public static class {cls}");
        sb.AppendLine("{");
        sb.AppendLine($"    private const string BasePath = \"{route}\";");
        sb.AppendLine($"    private const string Display = \"{Escape(model.Display)}\";");
        sb.AppendLine($"    private const string Singular = \"{Escape(model.Singular)}\";");
        sb.AppendLine("    private const int PageSize = 20;");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>The [ScaffoldSearch] properties, as declared names, handed to the store on every list.</summary>");
        // `new string[] { ... }` and not a collection expression: the emitted source
        // is compiled with the CONSUMER's LangVersion, and `[...]` needs C# 12.
        // Everything else the generator emits bottoms out at C# 9, so a collection
        // expression here would raise that floor for the whole generated file --
        // the same class of consumer-side break as relying on ImplicitUsings.
        sb.AppendLine($"    public static readonly string[] SearchFields = new string[] {{ {string.Join(", ", searchable.Select(p => "\"" + Escape(p.Name) + "\""))} }};");
        sb.AppendLine();

        EmitMap(sb, model, cls, form, route);
        EmitList(sb, model, type, listed, searchable);
        EmitNew(sb);
        EmitEdit(sb, type);
        EmitCreate(sb, type, form);
        EmitUpdate(sb, type, form);
        EmitDelete(sb, type);
        EmitFormHtml(sb, model, type, editable);

        sb.AppendLine("}");
        return sb.ToString();
    }

    // The self-binding form record: variant 5b from brainstorm 001 sec.12. It
    // carries its own content-type guard because an endpoint filter runs AFTER
    // argument binding and so cannot protect the bind.
    private static void EmitFormRecord(StringBuilder sb, ScaffoldModel model, string form, List<PropertyModel> editable)
    {
        sb.AppendLine($"/// <summary>The submitted form for <see cref=\"{model.FullyQualifiedName}\"/>, as a declared shape.</summary>");
        sb.AppendLine("/// <remarks>");
        sb.AppendLine("/// A field not declared here is not bound. That is Rails' strong-parameters");
        sb.AppendLine("/// guarantee, except the compiler enforces it: there is no allowlist to keep in");
        sb.AppendLine("/// sync, because the only way to bind a field is to declare it.");
        sb.AppendLine("/// </remarks>");
        sb.AppendLine($"public sealed record {form}(");
        for (int i = 0; i < editable.Count; i++)
        {
            sb.AppendLine($"    string? {editable[i].Name}{(i < editable.Count - 1 ? "," : ") : IBindableFromHttpContext<" + form + ">")}");
        }

        if (editable.Count == 0)
        {
            sb.AppendLine($"    string? _Unused) : IBindableFromHttpContext<{form}>");
        }

        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>The IBindableFromHttpContext entry point, for a hand-written handler that takes this type directly.</summary>");
        sb.AppendLine($"    public static async ValueTask<{form}?> BindAsync(HttpContext context, ParameterInfo parameter) =>");
        sb.AppendLine("        await ReadAsync(context).ConfigureAwait(false);");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Reads the form. What the generated request delegates call.</summary>");
        sb.AppendLine($"    public static async ValueTask<{form}> ReadAsync(HttpContext context)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (!context.Request.HasFormContentType)");
        sb.AppendLine("        {");
        sb.AppendLine("            // BadHttpRequestException carries its own status, which the host's");
        sb.AppendLine("            // error middleware surfaces. It has to be raised here rather than in a");
        sb.AppendLine("            // filter: binding runs first.");
        sb.AppendLine("            throw new BadHttpRequestException(\"Expected a form body.\", StatusCodes.Status415UnsupportedMediaType);");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        IFormCollection form = await context.Request.ReadFormAsync(context.RequestAborted).ConfigureAwait(false);");
        sb.AppendLine($"        return new {form}(");
        if (editable.Count == 0)
        {
            sb.AppendLine("            null);");
        }
        else
        {
            for (int i = 0; i < editable.Count; i++)
            {
                sb.AppendLine($"            form[\"{editable[i].FieldName}\"].ToString(){(i < editable.Count - 1 ? "," : ");")}");
            }
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void EmitMap(StringBuilder sb, ScaffoldModel model, string cls, string form, string route)
    {
        sb.AppendLine($"    /// <summary>Maps the generated {Escape(model.Display)} endpoints under <c>{route}</c>.</summary>");
        sb.AppendLine($"    public static IEndpointRouteBuilder Map{model.TypeName}Scaffold(this IEndpointRouteBuilder endpoints)");
        sb.AppendLine("    {");
        sb.AppendLine("        RouteGroupBuilder group = endpoints.MapGroup(BasePath);");
        sb.AppendLine();
        sb.AppendLine("        group.MapGet(\"/\", ScaffoldEndpoints.Handle(http => ListAsync(http, http.RequestAborted)))");
        sb.AppendLine($"            {Authorization(model, ScaffoldOperation.Read)};");
        sb.AppendLine();
        sb.AppendLine("        group.MapGet(\"/new\", ScaffoldEndpoints.Handle(http => Task.FromResult(NewPage(http))))");
        sb.AppendLine($"            {Authorization(model, ScaffoldOperation.Write)};");
        sb.AppendLine();
        sb.AppendLine("        group.MapPost(\"/\", ScaffoldEndpoints.Handle(http => CreateAsync(http, http.RequestAborted)))");
        sb.AppendLine($"            {Authorization(model, ScaffoldOperation.Write)}");
        sb.AppendLine("            .WithMetadata(RequiresAntiforgery.Instance);");
        sb.AppendLine();
        sb.AppendLine("        group.MapGet(\"/{id}\", ScaffoldEndpoints.Handle(http => EditAsync(ScaffoldEndpoints.RouteValue(http, \"id\"), http, http.RequestAborted)))");
        sb.AppendLine($"            {Authorization(model, ScaffoldOperation.Write)};");
        sb.AppendLine();
        sb.AppendLine("        group.MapPost(\"/{id}\", ScaffoldEndpoints.Handle(http => UpdateAsync(ScaffoldEndpoints.RouteValue(http, \"id\"), http, http.RequestAborted)))");
        sb.AppendLine($"            {Authorization(model, ScaffoldOperation.Write)}");
        sb.AppendLine("            .WithMetadata(RequiresAntiforgery.Instance);");
        sb.AppendLine();
        sb.AppendLine("        group.MapPost(\"/{id}/delete\", ScaffoldEndpoints.Handle(http => DeleteAsync(ScaffoldEndpoints.RouteValue(http, \"id\"), http, http.RequestAborted)))");
        sb.AppendLine($"            {Authorization(model, ScaffoldOperation.Delete)}");
        sb.AppendLine("            .WithMetadata(RequiresAntiforgery.Instance);");
        sb.AppendLine();
        sb.AppendLine("        return endpoints;");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    // [Auth] with nothing on it means "any authenticated user"; a Role becomes an
    // inline AuthorizeAttribute so the consumer does not have to register a named
    // policy for the common case; a Policy is passed straight through. No [Auth]
    // at all means the routes are open, which is a deliberate choice the consumer
    // makes by omission.
    private static string Authorization(ScaffoldModel model, ScaffoldOperation operation)
    {
        if (model.Auth is null)
        {
            return ".WithMetadata()";
        }

        if (!string.IsNullOrEmpty(model.Auth.Policy))
        {
            return $".RequireAuthorization(\"{Escape(model.Auth.Policy!)}\")";
        }

        string? role = model.Auth.RoleFor(operation);
        return string.IsNullOrEmpty(role)
            ? ".RequireAuthorization()"
            : $".RequireAuthorization(new Microsoft.AspNetCore.Authorization.AuthorizeAttribute {{ Roles = \"{Escape(role!)}\" }})";
    }

    private static void EmitList(StringBuilder sb, ScaffoldModel model, string type, List<PropertyModel> listed, List<PropertyModel> searchable)
    {
        sb.AppendLine("    private static async Task<IResult> ListAsync(HttpContext http, CancellationToken ct)");
        sb.AppendLine("    {");
        sb.AppendLine($"        IScaffoldStore<{type}> store = http.RequestServices.GetRequiredService<IScaffoldStore<{type}>>();");
        sb.AppendLine("        string? search = ScaffoldValues.Text(http.Request.Query[\"q\"].ToString());");
        // Clamped at both ends, not just the low one. ?page=2000000000 multiplied
        // by PageSize overflows a signed int and lands on a NEGATIVE skip, which an
        // unsuspecting store hands to Skip() or to OFFSET; the route is an
        // anonymous GET on an open model, so the input costs an attacker nothing.
        // MaxPage is int.MaxValue / PageSize, the largest page whose offset still
        // fits, so the arithmetic below cannot overflow whatever PageSize becomes.
        sb.AppendLine("        const int MaxPage = int.MaxValue / PageSize;");
        sb.AppendLine("        int page = Math.Clamp(ScaffoldValues.Int32(http.Request.Query[\"page\"].ToString(), 1), 1, MaxPage);");
        sb.AppendLine();
        sb.AppendLine($"        IReadOnlyList<{type}> rows = await store.ListAsync(search, SearchFields, (page - 1) * PageSize, PageSize, ct).ConfigureAwait(false);");
        sb.AppendLine("        int total = await store.CountAsync(search, SearchFields, ct).ConfigureAwait(false);");
        sb.AppendLine();
        sb.AppendLine("        StringBuilder sb = new(4096);");
        sb.AppendLine("        sb.Append(\"<div class=\\\"nws-head\\\"><h1>\").Append(Enc(Display)).Append(\"</h1>\");");
        sb.AppendLine("        sb.Append(\"<a class=\\\"nws-btn nws-btn--primary\\\" href=\\\"\").Append(BasePath).Append(\"/new\\\">New</a></div>\");");
        if (searchable.Count > 0)
        {
            sb.AppendLine("        sb.Append(\"<form class=\\\"nws-search\\\" method=\\\"get\\\" action=\\\"\").Append(BasePath).Append(\"\\\">\");");
            sb.AppendLine($"        sb.Append(\"<input type=\\\"search\\\" name=\\\"q\\\" placeholder=\\\"Search {Escape(string.Join(", ", searchable.Select(p => p.Label.ToLowerInvariant())))}\\\" value=\\\"\").Append(Enc(search ?? \"\")).Append(\"\\\">\");");
            sb.AppendLine("        sb.Append(\"<button type=\\\"submit\\\" class=\\\"nws-btn\\\">Search</button></form>\");");
        }

        sb.AppendLine("        sb.Append(\"<table class=\\\"nws-table\\\"><thead><tr>\");");
        foreach (PropertyModel p in listed)
        {
            sb.AppendLine($"        sb.Append(\"<th>{Escape(p.Label)}</th>\");");
        }

        sb.AppendLine("        sb.Append(\"<th class=\\\"nws-actions\\\"></th></tr></thead><tbody>\");");
        sb.AppendLine();
        sb.AppendLine("        if (rows.Count == 0)");
        sb.AppendLine("        {");
        sb.AppendLine($"            sb.Append(\"<tr><td class=\\\"nws-empty\\\" colspan=\\\"{listed.Count + 1}\\\">Nothing here yet.</td></tr>\");");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine($"        foreach ({type} row in rows)");
        sb.AppendLine("        {");
        sb.AppendLine($"            string id = ScaffoldValues.Display(row.{model.KeyProperty});");
        sb.AppendLine("            sb.Append(\"<tr>\");");
        foreach (PropertyModel p in listed)
        {
            sb.AppendLine($"            sb.Append(\"<td>\").Append(Enc(ScaffoldValues.Display(row.{p.Name}))).Append(\"</td>\");");
        }

        sb.AppendLine("            sb.Append(\"<td class=\\\"nws-actions\\\">\");");
        sb.AppendLine("            sb.Append(\"<a class=\\\"nws-btn nws-btn--sm\\\" href=\\\"\").Append(BasePath).Append('/').Append(Uri.EscapeDataString(id)).Append(\"\\\">Edit</a>\");");
        // data-nws-confirm, not onsubmit="return confirm(...)". An inline event
        // handler needs 'unsafe-hashes' in the CSP to run at all, and the
        // framework's own security headers do not grant it -- measured on
        // 2026-08-31, when apps/sample adopted the pipeline (spec 015 T8) and the
        // two delete e2e facts began reporting "the delete form did not raise a
        // confirm dialog at all". The attribute is read by the one nonced listener
        // ScaffoldLayout.Page emits.
        sb.AppendLine("            sb.Append(\"<form method=\\\"post\\\" action=\\\"\").Append(BasePath).Append('/').Append(Uri.EscapeDataString(id)).Append(\"/delete\\\" data-nws-confirm=\\\"Delete this record?\\\">\");");
        sb.AppendLine("            sb.Append(ScaffoldLayout.AntiforgeryField(http));");
        sb.AppendLine("            sb.Append(\"<button type=\\\"submit\\\" class=\\\"nws-btn nws-btn--sm nws-btn--danger\\\">Delete</button></form>\");");
        sb.AppendLine("            sb.Append(\"</td></tr>\");");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        sb.Append(\"</tbody></table>\");");
        sb.AppendLine("        sb.Append(ScaffoldLayout.Pager(BasePath, search, page, total, PageSize));");
        sb.AppendLine("        return ScaffoldLayout.Page(http, Display, sb.ToString());");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitNew(StringBuilder sb)
    {
        sb.AppendLine("    private static IResult NewPage(HttpContext http) =>");
        sb.AppendLine($"        ScaffoldLayout.Page(http, \"New \" + Singular, FormHtml(http, null, BasePath, \"Create\", null));");
        sb.AppendLine();
    }

    private static void EmitEdit(StringBuilder sb, string type)
    {
        sb.AppendLine("    private static async Task<IResult> EditAsync(string id, HttpContext http, CancellationToken ct)");
        sb.AppendLine("    {");
        sb.AppendLine($"        IScaffoldStore<{type}> store = http.RequestServices.GetRequiredService<IScaffoldStore<{type}>>();");
        sb.AppendLine($"        {type}? row = await store.GetAsync(id, ct).ConfigureAwait(false);");
        sb.AppendLine("        if (row is null)");
        sb.AppendLine("        {");
        sb.AppendLine("            return Results.NotFound();");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        return ScaffoldLayout.Page(http, \"Edit \" + Singular, FormHtml(http, row, BasePath + \"/\" + Uri.EscapeDataString(id), \"Save\", null));");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitCreate(StringBuilder sb, string type, string form)
    {
        sb.AppendLine("    private static async Task<IResult> CreateAsync(HttpContext http, CancellationToken ct)");
        sb.AppendLine("    {");
        sb.AppendLine($"        {form} form = await {form}.ReadAsync(http).ConfigureAwait(false);");
        sb.AppendLine($"        IScaffoldStore<{type}> store = http.RequestServices.GetRequiredService<IScaffoldStore<{type}>>();");
        sb.AppendLine("        var (item, error) = FromForm(form, null);");
        sb.AppendLine("        if (error is not null)");
        sb.AppendLine("        {");
        sb.AppendLine("            return ScaffoldLayout.Page(http, \"New \" + Singular, FormHtml(http, null, BasePath, \"Create\", error, form));");
        sb.AppendLine("        }");
        sb.AppendLine();
        // The returned key is used rather than discarded, and the redirect goes to
        // the new row. The store is the only party that can assign a unique key
        // (IScaffoldStore.CreateAsync says so), and a store that returns a stale or
        // empty one now shows it on the very next request instead of at the next
        // silent overwrite.
        sb.AppendLine("        string created = await store.CreateAsync(item, ct).ConfigureAwait(false);");
        // Without this, an empty key redirects to BasePath + "/" -- which is the
        // list route -- and a store that assigned no key looks like a successful
        // create. The guard is what makes the paragraph above true.
        sb.AppendLine("        if (string.IsNullOrEmpty(created))");
        sb.AppendLine("        {");
        sb.AppendLine($"            throw new InvalidOperationException(\"IScaffoldStore<{type}>.CreateAsync returned no key. The store assigns the key and must return it.\");");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        return Results.Redirect(BasePath + \"/\" + Uri.EscapeDataString(created));");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitUpdate(StringBuilder sb, string type, string form)
    {
        sb.AppendLine("    private static async Task<IResult> UpdateAsync(string id, HttpContext http, CancellationToken ct)");
        sb.AppendLine("    {");
        sb.AppendLine($"        {form} form = await {form}.ReadAsync(http).ConfigureAwait(false);");
        sb.AppendLine($"        IScaffoldStore<{type}> store = http.RequestServices.GetRequiredService<IScaffoldStore<{type}>>();");
        sb.AppendLine($"        {type}? existing = await store.GetAsync(id, ct).ConfigureAwait(false);");
        sb.AppendLine("        if (existing is null)");
        sb.AppendLine("        {");
        sb.AppendLine("            return Results.NotFound();");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        var (item, error) = FromForm(form, existing);");
        sb.AppendLine("        if (error is not null)");
        sb.AppendLine("        {");
        sb.AppendLine("            return ScaffoldLayout.Page(http, \"Edit \" + Singular, FormHtml(http, existing, BasePath + \"/\" + Uri.EscapeDataString(id), \"Save\", error, form));");
        sb.AppendLine("        }");
        sb.AppendLine();
        // The row was there when GetAsync ran and may not be when UpdateAsync does:
        // a concurrent delete between the two is one request, not a rare race. A
        // discarded false redirected to the list as if the edit had been saved.
        sb.AppendLine("        if (!await store.UpdateAsync(id, item, ct).ConfigureAwait(false))");
        sb.AppendLine("        {");
        sb.AppendLine("            return Results.NotFound();");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        return Results.Redirect(BasePath);");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitDelete(StringBuilder sb, string type)
    {
        sb.AppendLine("    private static async Task<IResult> DeleteAsync(string id, HttpContext http, CancellationToken ct)");
        sb.AppendLine("    {");
        sb.AppendLine($"        IScaffoldStore<{type}> store = http.RequestServices.GetRequiredService<IScaffoldStore<{type}>>();");
        // False means no such row. Redirecting anyway reported a deletion that did
        // not happen -- indistinguishable, from the browser, from one that did.
        sb.AppendLine("        if (!await store.DeleteAsync(id, ct).ConfigureAwait(false))");
        sb.AppendLine("        {");
        sb.AppendLine("            return Results.NotFound();");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        return Results.Redirect(BasePath);");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitFormHtml(StringBuilder sb, ScaffoldModel model, string type, List<PropertyModel> editable)
    {
        // Form -> model, with the key carried over from the existing row rather
        // than read from the submission. A key that round-trips through a form is
        // an id the client gets to choose.
        sb.AppendLine($"    private static ({type} Item, string? Error) FromForm({model.TypeName}Form form, {type}? existing)");
        sb.AppendLine("    {");
        foreach (PropertyModel p in editable)
        {
            if (IsStringLike(p) && !p.IsNullable)
            {
                sb.AppendLine($"        if (ScaffoldValues.Text(form.{p.Name}) is null)");
                sb.AppendLine("        {");
                sb.AppendLine($"            return (Build(form, existing), \"{Escape(p.Label)} is required.\");");
                sb.AppendLine("        }");
                sb.AppendLine();
                continue;
            }

            // Malformed input is an error the user is shown, not a fallback the
            // store keeps. Without this, "abc" in a number field was saved as 0 and
            // "not-a-date" as this instant, and the response was the same 302 a
            // valid submission gets -- the converters answer every failure with a
            // fallback, by design, so nothing downstream could tell the difference.
            // Blank still takes the fallback; only a value that cannot be read as
            // its declared type stops here.
            if (Validator(p) is (string check, string message))
            {
                sb.AppendLine($"        if (!ScaffoldValues.{check}(form.{p.Name}))");
                sb.AppendLine("        {");
                sb.AppendLine($"            return (Build(form, existing), \"{Escape(p.Label)} {message}\");");
                sb.AppendLine("        }");
                sb.AppendLine();
            }
        }

        sb.AppendLine("        return (Build(form, existing), null);");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine($"    private static {type} Build({model.TypeName}Form form, {type}? existing) => new()");
        sb.AppendLine("    {");
        sb.AppendLine($"        {model.KeyProperty} = existing is null ? default! : existing.{model.KeyProperty},");
        foreach (PropertyModel p in model.Properties)
        {
            if (p.Name == model.KeyProperty)
            {
                continue;
            }

            if (p.ReadOnly)
            {
                sb.AppendLine($"        {p.Name} = existing is null ? default! : existing.{p.Name},");
                continue;
            }

            sb.AppendLine($"        {p.Name} = {Convert(p) ?? throw new InvalidOperationException($"no conversion for {p.TypeName}")},");
        }

        sb.AppendLine("    };");
        sb.AppendLine();

        // `submitted` is the rejected form, and it is what an error page renders
        // from. Without it the redisplayed form showed Build's output, so
        // "Views must be a whole number." appeared next to a field reading 0 and a
        // rejected date next to this instant: the message and the value disagreed,
        // and the user could no longer see what they had typed. It also decides the
        // heading, because `row` is null on a rejected create, which is what makes
        // that page say "New" rather than "Edit".
        sb.AppendLine($"    private static string FormHtml(HttpContext http, {type}? row, string action, string submitLabel, string? error, {model.TypeName}Form? submitted = null)");
        sb.AppendLine("    {");
        sb.AppendLine("        StringBuilder sb = new(2048);");
        sb.AppendLine("        sb.Append(\"<div class=\\\"nws-head\\\"><h1>\").Append(Enc(row is null ? \"New \" + Singular : \"Edit \" + Singular)).Append(\"</h1>\");");
        sb.AppendLine("        sb.Append(\"<a class=\\\"nws-btn\\\" href=\\\"\").Append(BasePath).Append(\"\\\">Back</a></div>\");");
        sb.AppendLine("        if (error is not null)");
        sb.AppendLine("        {");
        sb.AppendLine("            sb.Append(\"<p class=\\\"nws-error\\\" role=\\\"alert\\\">\").Append(Enc(error)).Append(\"</p>\");");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        sb.Append(\"<form class=\\\"nws-form\\\" method=\\\"post\\\" action=\\\"\").Append(Enc(action)).Append(\"\\\">\");");
        sb.AppendLine("        sb.Append(ScaffoldLayout.AntiforgeryField(http));");
        foreach (PropertyModel p in editable)
        {
            // The submitted string wins over the stored value, so a rejected form
            // comes back carrying what the user typed.
            string value = $"submitted is not null ? (submitted.{p.Name} ?? \"\") : row is null ? \"\" : ScaffoldValues.Editable(row.{p.Name})";

            sb.AppendLine($"        sb.Append(\"<label for=\\\"{p.FieldName}\\\">{Escape(p.Label)}</label>\");");
            if (p.Multiline)
            {
                sb.AppendLine($"        sb.Append(\"<textarea id=\\\"{p.FieldName}\\\" name=\\\"{p.FieldName}\\\" rows=\\\"6\\\">\").Append(Enc({value})).Append(\"</textarea>\");");
            }
            else if (p.TypeName == "bool")
            {
                // `row.Flag == true` rather than `row is not null && row.Flag`:
                // for a `bool?` property the second is bool? in a && and does not
                // compile, which is the one gap the short/float pass left. Ticked
                // state comes from the submission when there is one, because an
                // unticked box submits nothing and must come back unticked.
                sb.AppendLine($"        sb.Append(\"<input type=\\\"checkbox\\\" id=\\\"{p.FieldName}\\\" name=\\\"{p.FieldName}\\\"\").Append((submitted is not null ? ScaffoldValues.Boolean(submitted.{p.Name}) : row?.{p.Name} == true) ? \" checked\" : \"\").Append(\">\");");
            }
            else
            {
                sb.AppendLine($"        sb.Append(\"<input type=\\\"{InputType(p)}\\\" id=\\\"{p.FieldName}\\\" name=\\\"{p.FieldName}\\\" value=\\\"\").Append(Enc({value})).Append(\"\\\">\");");
            }
        }

        sb.AppendLine("        sb.Append(\"<button type=\\\"submit\\\" class=\\\"nws-btn nws-btn--primary\\\">\").Append(Enc(submitLabel)).Append(\"</button>\");");
        sb.AppendLine("        sb.Append(\"</form>\");");
        sb.AppendLine("        return sb.ToString();");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    private static string Enc(string value) => HtmlEncoder.Default.Encode(value);");
    }

    private static bool IsStringLike(PropertyModel p) => p.TypeName == "string";

    // The ScaffoldValues check for a property's declared type, and the tail of the
    // message shown when it fails. Null for string and bool: a string cannot be
    // malformed, and an unticked checkbox submits nothing at all, so every value a
    // bool field can carry is meaningful.
    private static (string Check, string Message)? Validator(PropertyModel p) => p.TypeName switch
    {
        "short" => ("IsInt16", "must be a whole number."),
        "int" => ("IsInt32", "must be a whole number."),
        "long" => ("IsInt64", "must be a whole number."),
        "decimal" => ("IsDecimal", "must be a number."),
        "double" => ("IsDouble", "must be a number."),
        "float" => ("IsSingle", "must be a number."),
        "System.DateTime" => ("IsDateTime", "must be a date and time."),
        "System.Guid" => ("IsGuid", "must be a valid id."),
        _ => null,
    };

    private static string InputType(PropertyModel p) => p.TypeName switch
    {
        "int" or "long" or "short" => "number",
        "decimal" or "double" or "float" => "number\\\" step=\\\"any",
        "System.DateTime" => "datetime-local",
        _ => "text",
    };

    // Null means "this type has no form conversion", and the generator turns that
    // into a display-only property rather than an assignment. It is deliberately
    // the ONLY table of bindable types: the default arm used to emit
    // `ScaffoldValues.Text(form.X) ?? string.Empty` for anything it did not
    // recognise, which is a string assigned to a byte, a ushort, an enum,
    // a DateOnly, a TimeSpan or any type a consumer invents -- CS0029 in
    // generated code, on a model that had done nothing wrong. Closing that class
    // by listing more types only moves the edge; returning null closes it for
    // every type there will ever be.
    internal static string? Convert(PropertyModel p)
    {
        string raw = $"form.{p.Name}";
        return p.TypeName switch
        {
            "string" when p.IsNullable => $"ScaffoldValues.Text({raw})",
            "string" => $"ScaffoldValues.Text({raw}) ?? string.Empty",
            // short and float used to fall through to the string case at the
            // bottom, which emitted `Quantity = ScaffoldValues.Text(form.Quantity)
            // ?? string.Empty` -- a string assigned to a short, CS0029, on a model
            // that had done nothing wrong. InputType already knew both types; only
            // this table did not. Nullable double and nullable Guid failed the same
            // way, and neither appeared in the audit because no test model declared
            // one.
            "short" when p.IsNullable => $"ScaffoldValues.NullableInt16({raw})",
            "short" => $"ScaffoldValues.Int16({raw})",
            "int" when p.IsNullable => $"ScaffoldValues.NullableInt32({raw})",
            "int" => $"ScaffoldValues.Int32({raw})",
            "long" when p.IsNullable => $"ScaffoldValues.NullableInt64({raw})",
            "long" => $"ScaffoldValues.Int64({raw})",
            "decimal" when p.IsNullable => $"ScaffoldValues.NullableDecimal({raw})",
            "decimal" => $"ScaffoldValues.Decimal({raw})",
            "double" when p.IsNullable => $"ScaffoldValues.NullableDouble({raw})",
            "double" => $"ScaffoldValues.Double({raw})",
            "float" when p.IsNullable => $"ScaffoldValues.NullableSingle({raw})",
            "float" => $"ScaffoldValues.Single({raw})",
            "bool" => $"ScaffoldValues.Boolean({raw})",
            "System.DateTime" when p.IsNullable => $"ScaffoldValues.NullableDateTime({raw})",
            "System.DateTime" => $"ScaffoldValues.DateTimeValue({raw}, DateTime.UtcNow)",
            "System.Guid" when p.IsNullable => $"ScaffoldValues.NullableGuid({raw})",
            "System.Guid" => $"ScaffoldValues.GuidValue({raw})",
            _ => null,
        };
    }

    // A C# string literal, or the null literal. Used where the emitted call takes a
    // string? and the model may not have supplied one.
    private static string Literal(string? value) =>
        value is null ? "null" : "\"" + Escape(value) + "\"";

    private static string Escape(string value) =>
        value.Replace("\\", "\\\\").Replace("\"", "\\\"");

    // The shared chrome: one page shell, one stylesheet, the antiforgery field and
    // the pager. Emitted once no matter how many models are scaffolded.
    public static string EmitRuntime(List<ScaffoldModel> models, string root)
    {
