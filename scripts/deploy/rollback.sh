#!/usr/bin/env bash
#
# Returns production to the previous release. Spec 011 T10 (R11).
#
#   sudo scripts/deploy/rollback.sh            # show what would happen
#   sudo scripts/deploy/rollback.sh --execute  # do it
#
# This is a Caddy reload and nothing else. The previous colour is still running
# -- deploy.sh leaves it up precisely so that rollback costs one reload -- so
# there is no unpack, no restart and no database action. That is also the limit:
# a release that applied migrations cannot be rolled back this way, and this
# script refuses rather than half-doing it.
#
# Bare invocation is the dry run, per the repo-wide cleanup-script interface.

set -euo pipefail

BLUE_PORT=5011
GREEN_PORT=5012
UPSTREAM_FILE=/etc/caddy/upstream.caddy
DEPLOY_LOG=/var/lib/nativeweb/deployments.log
EXECUTE=0

die() {
	echo "rollback.sh: $*" >&2
	exit 1
}

for arg in "$@"; do
	case "$arg" in
	--execute | -e) EXECUTE=1 ;;
	-h | --help)
		sed -n '2,17p' "${BASH_SOURCE[0]}"
		exit 0
		;;
	*) die "unknown argument '$arg'" ;;
	esac
done

[[ "$(id -u)" -eq 0 ]] || die "must run as root (writes $UPSTREAM_FILE and reloads caddy)"
[[ -f "$DEPLOY_LOG" ]] || die "no deployment log at $DEPLOY_LOG -- nothing has been promoted on this host"

# `|| true` is required, not decorative: under `pipefail` a non-matching grep
# makes the whole substitution non-zero, `set -e` exits on the assignment, and
# the friendly message below is unreachable -- an empty-but-present log used to
# produce a bare exit 1.
LAST="$(grep -P '\tpromote\t' "$DEPLOY_LOG" | tail -1 || true)"
[[ -n "$LAST" ]] || die "no promotion recorded -- nothing to roll back to"

CURRENT_COLOUR="$(cut -f3 <<<"$LAST")"
CURRENT_SHA="$(cut -f4 <<<"$LAST")"
SCHEMA_CHANGED="$(cut -f5 <<<"$LAST" | cut -d= -f2)"
PREVIOUS_SHA="$(cut -f6 <<<"$LAST" | cut -d= -f2)"
PREVIOUS_COLOUR="$([[ "$CURRENT_COLOUR" == blue ]] && echo green || echo blue)"
PREVIOUS_PORT="$([[ "$PREVIOUS_COLOUR" == blue ]] && echo "$BLUE_PORT" || echo "$GREEN_PORT")"

# What is ACTUALLY serving, from the file Caddy imports -- not from the last
# promote line. The log's last promotion is not the current state after a
# rollback (this script appends a `rollback` line the grep above skips) or after
# any hand edit of the upstream file, and rolling back from a state you have
# misread is how one bad release becomes two.
SERVING_PORT="$(grep -E '^\s*reverse_proxy\s' "$UPSTREAM_FILE" 2>/dev/null |
	grep -oE '127\.0\.0\.1:[0-9]+' | head -1 | cut -d: -f2 || true)"
case "$SERVING_PORT" in
"$BLUE_PORT") SERVING_COLOUR=blue ;;
"$GREEN_PORT") SERVING_COLOUR=green ;;
*) SERVING_COLOUR="" ;;
esac

if [[ -n "$SERVING_COLOUR" && "$SERVING_COLOUR" != "$CURRENT_COLOUR" ]]; then
	die "the deployment log says $CURRENT_COLOUR is live, but $UPSTREAM_FILE points at $SERVING_COLOUR.
       Something other than deploy.sh changed what is serving -- a previous rollback, or a hand
       edit. Refusing to guess which is right: reconcile them first, because rolling back from a
       misread state promotes a release nobody chose."
fi

# --- The refusal that matters -----------------------------------------------
#
# Rolling the binary back while the schema stays forward is only safe when the
# migration was an expand. This script cannot tell an expand from a contract --
# nothing in schema_migrations records intent -- so it refuses the whole class
# and hands the decision to a person, with the release named.
if [[ "$SCHEMA_CHANGED" == "1" ]]; then
	die "release $CURRENT_SHA applied database migrations.
       Pointing Caddy back at $PREVIOUS_COLOUR would run $PREVIOUS_SHA against a schema it was
       never built for. If those migrations were purely additive, roll back by hand and say so
       in the deployment log. If they were not, the way back is a forward release that reverses
       them -- not this script.
       Migrations in that release: compare schema_migrations against $PREVIOUS_SHA's db/migrations."
fi

[[ -n "$PREVIOUS_SHA" ]] || die "release $CURRENT_SHA was the first on this host -- there is nothing behind it"

PREVIOUS_STATE="$(systemctl is-active "nativeweb@$PREVIOUS_COLOUR" || true)"
if [[ "$PREVIOUS_STATE" != "active" ]]; then
	die "nativeweb@$PREVIOUS_COLOUR is '$PREVIOUS_STATE', not active.
       deploy.sh leaves the previous colour running so rollback is a reload; if it has been
       stopped, this is a redeploy of $PREVIOUS_SHA rather than a rollback."
fi

echo "rollback.sh: live now      $CURRENT_COLOUR  $CURRENT_SHA"
echo "rollback.sh: would revert  $PREVIOUS_COLOUR  $PREVIOUS_SHA  (port $PREVIOUS_PORT)"
echo "rollback.sh: no database action -- that release applied no migrations."

if [[ "$EXECUTE" -ne 1 ]]; then
	echo
	echo "rollback.sh: DRY RUN. Nothing changed. Re-run with --execute to apply."
	exit 0
fi

cat >"$UPSTREAM_FILE" <<EOF
# Generated by rollback.sh -- do not edit. Live colour: $PREVIOUS_COLOUR ($PREVIOUS_SHA)
reverse_proxy 127.0.0.1:$PREVIOUS_PORT
EOF

systemctl reload caddy

printf '%s\trollback\t%s\t%s\tschema_changed=0\tprevious=%s\n' \
	"$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$PREVIOUS_COLOUR" "$PREVIOUS_SHA" "$CURRENT_SHA" \
	>>"$DEPLOY_LOG"

echo "rollback.sh: $PREVIOUS_SHA is live on $PREVIOUS_COLOUR."
