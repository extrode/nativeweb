# 011-production-deployment.ps1 -- cleanup after spec 011, the production deploy
# infrastructure. Written 2026-08-27 from the NativeWeb
# feat/011-production-deployment branch.
#
# Most of what this work produced is not cleanup at all: scripts/deploy/,
# docs/02-reference/deployment.md and the tests are committed source, and the
# scratch under the repo's own tmp/ is mine to delete per AGENTS.md -- the
# linux-x64 publish in tmp/t14-publish, tmp/011-code.diff and tmp/t14-probe.sh
# have been removed already and are deliberately absent below.
#
# What is left is in two places I do not own: the Release build residue this
# repo now carries for a SECOND runtime, and a handful of files inside the
# Debian WSL image, where "the project's own tmp/" does not reach.
#
# Dry run is the default and always exits 0. --execute / -e is the only way to
# act. Two things past that are irreversible and need their own second flag:
#   -RemoveLinuxBuildOutput   deletes the linux-x64 Release publish trees this
#                             work added under apps/ and libs/ (they rebuild)
#   -RemoveWslScratch         deletes ~/t14, ~/t14-probe.sh, ~/dlprobe and
#                             ~/dlprobe.c inside the Debian WSL image
#
# Kept deliberately (do NOT add here):
#   - scripts/deploy/ and everything under it. That IS the deliverable.
#   - the win-x64/Debug trees. Ordinary local dev output, unrelated to 011.
#   - the transient systemd units nw-mdwe-on / nw-mdwe-off / nw-mdwe-check /
#     dlprobe from the T14 measurement. They were run with --collect and are
#     already gone; `systemctl --user list-units` will not show them.
#   - dist/. build.sh writes there, and the one truncated artifact this work
#     produced was removed when the defect that made it was fixed.

param(
    [Alias('e')][switch]$Execute,
    [switch]$RemoveLinuxBuildOutput,
    [switch]$RemoveWslScratch,
    [Parameter(ValueFromRemainingArguments = $true)][string[]]$Rest
)

$ErrorActionPreference = 'Stop'

# rev-parse --verify --quiet and branch -d are both expected to exit non-zero,
# and whether a non-zero native exit throws under 'Stop' has moved between
# PowerShell versions. Pin it, or the handling below silently never runs.
$PSNativeCommandUseErrorActionPreference = $false

foreach ($a in $Rest) {
    switch ($a) {
        '--execute' { $Execute = $true }
        default { Write-Host "unknown argument: $a" -ForegroundColor Red; exit 2 }
    }
}

$repo = 'C:\home\code\extrode.com\nativeweb'
$failed = $false

# Context, reported and not refused on -- same reasoning as 010's script. This
# one deletes no source, `git branch -d` compares commits better than any string
# check written here, and a gate that refuses until the branch merges would
# refuse every run of the script's own working life.
$branch = git -C $repo branch --show-current
if (git -C $repo status --porcelain) {
    Write-Host "note: $repo has uncommitted changes. Nothing below touches tracked files."
}

function Act($desc, [scriptblock]$action) {
    if ($Execute) { Write-Host "DO   $desc"; & $action } else { Write-Host "would $desc" }
}

Write-Host '-- 1. worktrees'
# This work created none; it ran in the main tree. The prune clears a stale
# registration if one survived an earlier run.
Act 'git worktree prune' { git -C $repo worktree prune }

Write-Host '-- 2. merged branches (git branch -d refuses if unmerged)'
foreach ($b in @('feat/011-production-deployment')) {
    git -C $repo rev-parse --verify --quiet "refs/heads/$b" | Out-Null
    if ($LASTEXITCODE -ne 0) {
        Write-Host "  skip $b (no such branch)"
        continue
    }

    Act "git branch -d $b" {
        git -C $repo branch -d $b
        if ($LASTEXITCODE -ne 0) {
            Write-Host '  refused (git said why, above). Left alone.'
            $script:failed = $true
        }
    }
}

Write-Host '-- 3. linux-x64 Release build output (needs -RemoveLinuxBuildOutput)'
# New with this work: until 011 nothing here had ever been published for Linux,
# so bin/Release/net10.0/linux-x64 and its obj/ sibling did not exist. A
# NativeAOT publish leaves the ILCompiler intermediates behind as well, which is
# the bulk of it. All of it is regenerated by scripts/deploy/build.sh; none of it
# is referenced by any test.
$linuxTrees = @(
    Get-ChildItem -Path $repo -Recurse -Directory -Filter 'linux-x64' -ErrorAction SilentlyContinue |
        Where-Object { $_.FullName -match '\\(bin|obj)\\' -and $_.FullName -notmatch '\\tmp\\' }
)
$linuxBytes = ($linuxTrees | ForEach-Object {
        (Get-ChildItem $_.FullName -Recurse -File -ErrorAction SilentlyContinue |
            Measure-Object Length -Sum).Sum
    } | Measure-Object -Sum).Sum

if ($linuxTrees.Count -eq 0) {
    Write-Host '  skip: no linux-x64 build trees present'
}
elseif ($RemoveLinuxBuildOutput) {
    foreach ($t in $linuxTrees) {
        Act "remove $($t.FullName)" { Remove-Item -Recurse -Force $t.FullName }
    }
}
else {
    Write-Host ("  skip {0} linux-x64 tree(s), {1:N0} MB -- pass -RemoveLinuxBuildOutput as well" -f `
            $linuxTrees.Count, ($linuxBytes / 1MB))
    $linuxTrees | ForEach-Object { Write-Host "       $($_.FullName)" }
}

Write-Host '-- 4. WSL scratch from the T14 measurement (needs -RemoveWslScratch)'
# Outside the repo, so outside what AGENTS.md lets me delete on my own: the
# staged copy of the linux-x64 publish (~/t14, about 40 MB), the probe script
# that booted it under MemoryDenyWriteExecute, and the three-line C program plus
# its binary that proved dlopen of libsodium.so survives the same filter.
$wslPaths = @('$HOME/t14', '$HOME/t14-probe.sh', '$HOME/dlprobe', '$HOME/dlprobe.c')
if ($RemoveWslScratch) {
    foreach ($p in $wslPaths) {
        Act "wsl rm -rf $p" { wsl.exe -d Debian -- bash -lc "rm -rf $p" }
    }
}
else {
    Write-Host '  skip -- pass -RemoveWslScratch as well. Present now:'
    wsl.exe -d Debian -- bash -lc 'ls -ld ~/t14 ~/t14-probe.sh ~/dlprobe ~/dlprobe.c 2>/dev/null || echo "       (none present)"'
}

Write-Host ''
Write-Host '-- remaining state'
Write-Host "branch:      $(git -C $repo branch --show-current)"
Write-Host "worktrees:   $((git -C $repo worktree list) -join '; ')"
Write-Host "merged refs: $((git -C $repo branch --merged dev | Where-Object { $_ -notmatch '^\*|dev$|main$' }).Count) still present"
Write-Host "dist/:       $((Get-ChildItem "$repo\dist" -ErrorAction SilentlyContinue | Select-Object -ExpandProperty Name) -join ', ')"

if ($Execute -and $failed) { exit 1 }
