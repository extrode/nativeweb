<#
.SYNOPSIS
Removes what building spec 029 left behind.

.DESCRIPTION
Written 2026-09-05 at the end of feat/029-framework-templates. Bare invocation is a dry run: it
lists what would go and changes nothing. Pass -Execute (-e) to act.

Candidates, each checked at run time rather than asserted here:

  the merged branch      feat/029-framework-templates, only once
                         `git merge-base --is-ancestor <branch> dev` says it reached dev.
                         `git branch -d` is not that check: git accepts a branch merged to its
                         own upstream, so a pushed-but-unmerged branch deletes with a warning.

  artifacts/packages/    Thirteen .nupkg files from the tools/pack.ts runs that proved
                         NativeWeb.Web carries its four templates. Regenerated by one command;
                         the directory is gitignored.

  tmp/stamp-029/         The stamped product this branch's T10 built. A full checkout with its
                         own git repository and its own build output, and stamp-check refuses a
                         destination that is not empty, so one accumulates per run.

  tmp/029-review.diff    The diff handed to the two review lenses.

Not listed, and deliberately:

  tmp/stamp-check/       Named by scripts/cleanup/skeleton-stamp-check.ps1, which owns it. Two
                         scripts removing one directory is one script racing the other.

  libs/nativeweb.web/templates/
                         The deliverable.
#>
[CmdletBinding()]
param(
    [Alias('e')]
    [switch]$Execute
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$PSNativeCommandUseErrorActionPreference = $false

$repo = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$script:failed = $false

$branch = (git -C $repo rev-parse --abbrev-ref HEAD).Trim()
if ($branch -ne 'dev') {
    Write-Host "refuse: run this from dev, not from '$branch'. Nothing changed."
    exit 1
}

function Step([string]$label, [scriptblock]$act) {
    if ($Execute) {
        Write-Host "run:   $label"
        & $act
    }
    else {
        Write-Host "would: $label"
    }
}

$target = 'feat/029-framework-templates'

if (-not (git -C $repo rev-parse --verify --quiet "refs/heads/$target")) {
    Write-Host "skip:  branch $target no longer exists"
}
else {
    git -C $repo merge-base --is-ancestor $target dev
    if ($LASTEXITCODE -ne 0) {
        Write-Host "skip:  $target is not merged into dev. Left alone."
        $script:failed = $true
    }
    else {
        Step "git branch -d $target" {
            git -C $repo branch -d $target
            if ($LASTEXITCODE -ne 0) {
                Write-Host '  refused: git would not delete it. Left alone.'
                $script:failed = $true
            }
        }
    }
}

Write-Host ''

$scratch = @()

$packages = Join-Path $repo 'artifacts/packages'
if (Test-Path $packages) {
    $scratch += @(Get-ChildItem -Path $packages -Filter '*.nupkg' -File)
}

foreach ($relative in @('tmp/stamp-029', 'tmp/029-review.diff')) {
    $path = Join-Path $repo $relative
    if (Test-Path $path) {
        $scratch += @(Get-Item -Path $path)
    }
}

if ($scratch.Count -eq 0) {
    Write-Host 'skip:  no build scratch from this branch remains'
}

foreach ($item in $scratch) {
    $mb = if ($item.PSIsContainer) {
        [int]((Get-ChildItem -Path $item.FullName -File -Recurse -ErrorAction SilentlyContinue |
                Measure-Object -Property Length -Sum).Sum / 1MB)
    }
    else {
        [int]($item.Length / 1MB)
    }

    Step "remove $($item.FullName) ($mb MB)" {
        Remove-Item -Path $item.FullName -Recurse -Force
    }
}

if (-not $Execute) {
    Write-Host ''
    Write-Host 'Dry run: nothing was changed. Pass -Execute to act.'
}

exit ([int]$script:failed)
